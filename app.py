    st.markdown("### 🧮 Theoretical & Mathematical Formulation")
    m_col1, m_col2 = st.columns(2)
    with m_col1:
        st.markdown(r"""
        **1. Why Isolation Forest for Insurance Fraud?**
        - Standard supervised learning struggles in insurance because fraud cases are **heavily imbalanced** (often < 10%) and fraudulent patterns evolve continuously.
        - Isolation Forest explicitly isolates anomalies instead of profiling normal points.
        - **Core Axiom:** Anomalies are 'few and different'. Hence, in random recursive partitioning, anomalous instances are isolated closer to the root of the tree (shorter path lengths $h(x)$).
        
        **2. Average Path Length Formulation:**
        Given $n$ samples, the average path length of an unsuccessful search in a Binary Search Tree (BST) is:
        $$c(n) = 2 \left( \ln(n - 1) + 0.5772156649 \right) - \frac{2(n - 1)}{n}$$
        where $0.5772156649$ is Euler's constant.
        """)
    with m_col2:
        st.markdown("""
        **3. Anomaly Score Formula:**
        The anomaly score $s(x, n)$ for an insurance claim $x$ across an ensemble of $t$ isolation trees is:
        $$s(x, n) = 2^{-\frac{E(h(x))}{c(n)}}$$
        where $E(h(x))$ is the expected path length of claim $x$ over all isolation trees.
        
        **Interpretation Boundaries:**
        - When $E(h(x)) \\to 0$, $s \\to 1$: **Strong Anomaly / High Fraud Risk**
        - When $E(h(x)) \\to c(n)$, $s \\to 0.5$: Instance has no distinct anomaly pattern
        - When $E(h(x)) \\to n - 1$, $s \\to 0$: Standard normal legitimate claim
        """)

